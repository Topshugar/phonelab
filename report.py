import os
import shutil
import subprocess
from datetime import datetime

def has_adb():
    return shutil.which("adb") is not None

def get_prop(key):
    try:
        cmd = f"adb shell getprop {key}" if has_adb() else f"getprop {key}"
        return subprocess.check_output(cmd, shell=True, text=True).strip()
    except:
        return "Unknown"

def generate(video):
    if not os.path.exists(video):
        print(f"Video not found: {video}")
        return
    
    mode = "Termux ADB (main)" if has_adb() else "LADB direct (alternative)"
    model = get_prop("ro.product.model")
    android = get_prop("ro.build.version.release")
    ts = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    fname = os.path.basename(video)
    
    print(f"[Mode] {mode}")
    
    html = f"""<!DOCTYPE html><html><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>PhoneLab {ts}</title>
<style>body{{font-family:monospace;background:#0a0a0a;color:#0f0;padding:20px;max-width:900px;margin:auto}}
.card{{border:1px solid #0f0;padding:15px;margin:15px 0;background:#111}} video{{width:100%;border:1px solid #0f0}}</style>
</head><body>
<h1>PhoneLab Report</h1>
<div class="card">Mode: {mode}<br>QA PASSED | {ts}<br>Device: {model}<br>Android: {android}<br>File: {fname}</div>
<div class="card"><h3>Recording</h3><video controls src="{fname}"></video></div>
<div class="card">Generated by PhoneLab v0.2</div>
</body></html>"""
    
    report = f"./recordings/report_{datetime.now().strftime('%Y%m%d_%H%M%S')}.html"
    os.makedirs("./recordings", exist_ok=True)
    with open(report, "w") as f:
        f.write(html)
    
    import shutil as sh
    dest = os.path.join(os.path.dirname(report), fname)
    if video != dest:
        sh.copy(video, dest)
    
    print(f"✅ {report}")

if __name__ == "__main__":
    import sys
    if len(sys.argv) < 2:
        print("Usage: python report.py <video>")
    else:
        generate(sys.argv[1])